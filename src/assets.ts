import { AssetType, defineAssets } from '@iwsdk/core';
import { withBuildId } from './build-id.js';
import {
  IMPORTED_OBJECTS,
  objectAssetId,
  objectFile,
} from './imported-objects.js';
import { ROOM_PIECES, roomAssetId, roomFile } from './room-pieces.js';
import {
  createAnswerOrb,
  createAnswerTray,
  createPuzzleTable,
  createPuzzleTile,
} from './scene-assets/puzzle.scene-asset.js';
import { createRush } from './scene-assets/rush.scene-asset.js';
import { createScreenProjector } from './scene-assets/screen-projector.scene-asset.js';
import {
  createStage,
  createStudioFloor,
} from './scene-assets/studio.scene-asset.js';

const publicAssetUrl = (filePath: string): string =>
  withBuildId(`${import.meta.env.BASE_URL}${filePath.replace(/^\/+/u, '')}`);
const uikitml = (fileName: string, name: string) => ({
  url: publicAssetUrl(`ui/${fileName}`),
  type: AssetType.UIKitML,
  name,
});

export default defineAssets({
  'studio-floor': createStudioFloor(),
  stage: createStage(),
  // The owner's set dressing for the two back corners (src/room-pieces.ts),
  // in the background: the room is ready to play before they arrive.
  ...Object.fromEntries(
    ROOM_PIECES.map((piece) => [
      roomAssetId(piece),
      {
        url: publicAssetUrl(roomFile(piece)),
        type: AssetType.GLTF,
        priority: 'background' as const,
        name: `Room: ${piece}`,
      },
    ]),
  ),
  'puzzle-table': createPuzzleTable(),
  'answer-tray': createAnswerTray(),
  'puzzle-tile': createPuzzleTile(),
  // Generated by the owner in Meshy, optimized by scripts/optimize-model.mjs
  // (art/SOURCES.md). Critical, so it is ready before the table is set.
  'display-stand': {
    url: publicAssetUrl('models/display-stand.glb'),
    type: AssetType.GLTF,
    priority: 'critical',
    name: 'Display Stand',
  },
  'answer-orb': createAnswerOrb(),
  'screen-projector': createScreenProjector(),
  rush: createRush(),
  // Loaded in the background so the game starts fast; a miniature still
  // loading shows its code-built version for that round.
  ...Object.fromEntries(
    IMPORTED_OBJECTS.map((model) => [
      objectAssetId(model),
      {
        url: publicAssetUrl(objectFile(model)),
        type: AssetType.GLTF,
        priority: 'background' as const,
        name: `Object: ${model}`,
      },
    ]),
  ),
  screen: uikitml('screen.uikitml', 'Screen'),
  'tile-label': uikitml('tile-label.uikitml', 'Tile Label'),
  'orb-label': uikitml('orb-label.uikitml', 'Orb Label'),
});
